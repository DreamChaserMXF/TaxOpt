function labelForSlug(slug) {
  const dashIndex = slug.indexOf('-')
  const provinceKey = dashIndex >= 0 ? slug.slice(0, dashIndex) : slug
  const cityKey = dashIndex >= 0 ? slug.slice(dashIndex + 1) : ''
  const province = PROVINCE_LABEL[provinceKey] || provinceKey
  const city = CITY_LABEL[cityKey] || cityKey
  return { province, city, label: city ? `${province} · ${city}` : province }
}

export function listPresetSummaries() {
  return Object.keys(PRESET_CONFIGS).sort().map((slug) => {
    const info = labelForSlug(slug)
    return { slug, label: info.label, province: info.province }
  })
}

export function getPresetConfig(slug) {
  const config = PRESET_CONFIGS[slug]
  return config ? { ...config } : null
}
